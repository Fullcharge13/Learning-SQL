// 2장 「원하는 칸만」 (설계 §6: 열 고르기, AS, 계산 열 / 장터 예: 값 두 배로 올린 가격표).
// 쓰기 안내: docs/lesson-writing-guide.md · 점검: node tests/content.js --chapter 2
// 2장 낱말은 1장(SELECT·FROM·*)에 AS와 계산 기호 + - * / 를 더한 것이다. 조건(3장)·줄 세우기(5장)는 쓰지 않는다.
// - * 의 두 뜻: SELECT 바로 뒤에 혼자 서면 「모든 열」, 값 사이에 있으면 곱하기(2-2 카드에서 나란히 보여 줌).
// - 별칭은 영어 소문자와 밑줄(double_price, new_price, stock_value). 화면 비교는 열 이름도 보므로,
//   곱하기·더하기처럼 앞뒤를 바꿔도 같은 셈(2 * price)이 정답이 되도록 조립 정답의 계산 열에는 별칭을 붙인다.
//   별칭 없는 계산 열 조립(2-2)은 앞뒤를 바꾸면 값이 달라지는 빼기(price - 5)로 쓴다.
// - 헷갈림 카드에 + 는 쓰지 않는다: price * + 2 처럼 끼우면 「+2」로 읽혀 정답과 같은 결과가 된다.
// - stock 열에는 빈칸(NULL) 3개가 있어 price * stock 결과도 3행이 NULL이다. 2-4 카드에서 「6장에서」라고 짚어 둔다.
// - 이 장터(SQLite)는 정수끼리 나누면 소수점 아래를 버린다(수육 25 / 2 = 12). 엔진마다 다른 것은 「이 장터에서는」으로 쓴다(판정 R36). 2-4 카드에서 짚고, 실수 나눗셈(CAST)은 9장.
// - 조립 정답은 50행 이하라 items(40행)·shops(8행)만 쓴다.
